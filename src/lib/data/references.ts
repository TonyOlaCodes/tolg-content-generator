export function getReference(id: string): ReferenceEntry | undefined {
  return REFERENCES.find((r) => r.id === id);
}

export function searchReferences(query: string, category?: string): ReferenceEntry[] {
  const q = query.trim().toLowerCase();
  return REFERENCES.filter((r) => {
    if (category && category !== "all" && r.category !== category) return false;
    if (!q) return true;
    const blob = [r.name, ...r.aliases, ...r.knownFor, ...r.associatedWords, r.shortDescription]
      .join(" ")
      .toLowerCase();
    return blob.includes(q);
  });
}
