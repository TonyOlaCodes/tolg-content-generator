/**
 * Guests. They arrive through the front doors, walk an inspection route with
 * pauses, and raise the exposure meter when they can actually *see* the
 * elephant. Closed doors, walls and a crowd of employees standing in the way all
 * block that sight-line, which is what makes hiding it a real team effort.
 */

import {
  CROWD_COVER_FACTOR,
  CROWD_COVER_RADIUS,
  EXPOSURE_RATE,
  EXPOSURE_RATE_MANAGER,
  EXPOSURE_RATE_VIP,
} from "../game/config";
import { GUEST_COMPLAINTS as COMPLAINTS, GUEST_NAMES as NAMES } from "../game/content";
import { gameMap } from "../game/map";
import type { Guest, GuestKind } from "./state";
import type { Room } from "./room";

export { COMPLAINTS as GUEST_LINES };

export interface GuestTickResult {
  /** extra exposure per second generated by sightings this tick */
  exposurePerSecond: number;
  /** the closest employee to the elephant for each guest that saw it */
  sightings: { guestId: string; witnessId: string | null }[];
}

export function spawnGuest(room: Room, kind: GuestKind, spawnZone?: { x: number; y: number }): Guest | null {
  const id = `g${room.nextGuestId++}`;
  const start = spawnZone ?? { x: 39, y: 13.5 };
  const name = room.rng.pick(kind === "vip" ? NAMES.slice(0, 6) : NAMES);
  const guest: Guest = {
    id,
    name: kind === "manager" ? "The Manager" : kind === "vip" ? `${name} (VIP)` : name,
    kind,
    x: start.x * 32 + 16,
    y: start.y * 32 + 16,
    dir: 1,
    moving: false,
    path: [],
    step: 0,
    dwellUntil: 0,
    alarmed: false,
    alarmedUntil: 0,
    soothedUntil: 0,
    sight: kind === "vip" ? 8 : kind === "manager" ? 7 : 6,
    leaving: false,
    investigate: null,
    spawnedAt: room.now(),
    loops: 0,
    lastCountedAt: 0,
  };
  room.guests.push(guest);
  room.addFeed(
    kind === "vip"
      ? `👑 ${guest.name} has arrived and is looking around very carefully.`
      : kind === "manager"
        ? "📋 The Manager has entered the building."
        : `🛎 ${guest.name} arrived and headed inside.`,
    kind === "guest" ? "guest" : "warn",
    kind === "vip" ? "vip" : "ding",
  );
  return guest;
}

function waypointFor(room: Room, guest: Guest): { x: number; y: number; dwell: number } {
  const route = room.guestRoute;
  const entry = route[guest.step % route.length];
  return entry;
}

export function guestTick(room: Room, dt: number): GuestTickResult {
  const now = room.now();
  const result: GuestTickResult = { exposurePerSecond: 0, sightings: [] };
  const darkZones = room.darkZones(now);

  for (const guest of [...room.guests]) {
    // leaving guests walk out and disappear
    if (guest.leaving) {
      const exitX = 39 * 32;
      const exitY = 13.5 * 32;
      const dx = exitX - guest.x;
      const dy = exitY - guest.y;
      const distance = Math.hypot(dx, dy);
      if (distance < 20) {
        room.guests = room.guests.filter((entry) => entry.id !== guest.id);
        room.complaints = room.complaints.filter((entry) => entry.guestId !== guest.id);
        continue;
      }
      const step = 2.6 * 32 * dt;
      guest.x += (dx / distance) * step;
      guest.y += (dy / distance) * step;
      guest.dir = Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? 3 : 1) : dy > 0 ? 0 : 2;
      guest.moving = true;
      continue;
    }

    // choose a destination
    if (guest.path.length === 0 && now >= guest.dwellUntil) {
      let target: { x: number; y: number } | null = null;
      if (guest.investigate && guest.investigate.until > now) {
        target = { x: Math.floor(guest.investigate.x / 32), y: Math.floor(guest.investigate.y / 32) };
      } else {
        guest.investigate = null;
        if (guest.alarmed) {
          guest.leaving = true;
          continue;
        }
        const waypoint = waypointFor(room, guest);
        target = { x: waypoint.x, y: waypoint.y };
      }
      const tile = {
        x: Math.floor(guest.x / 32),
        y: Math.floor(guest.y / 32),
      };
      guest.path = gameMap.findPath(tile, target, room.doors) ?? [];
      if (guest.path.length === 0) {
        // already there: dwell then move on
        const waypoint = waypointFor(room, guest);
        guest.dwellUntil = now + Math.max(1200, waypoint.dwell * 1000 * (guest.investigate ? 0.5 : 1));
        guest.step += 1;
        if (guest.step >= room.guestRoute.length) {
          guest.step = 0;
          guest.loops += 1;
          if (guest.loops >= 1) {
            guest.leaving = true;
          }
        }
      }
    }

    if (guest.path.length > 0) {
      const node = guest.path[0];
      const targetX = node.x * 32 + 16;
      const targetY = node.y * 32 + 16;
      const dx = targetX - guest.x;
      const dy = targetY - guest.y;
      const distance = Math.hypot(dx, dy);
      const speed = (guest.alarmed ? 3.4 : guest.kind === "vip" ? 2.2 : 1.9) * 32;
      const step = speed * dt;
      if (distance <= step) {
        guest.x = targetX;
        guest.y = targetY;
        guest.path.shift();
        if (guest.path.length === 0) {
          const waypoint = waypointFor(room, guest);
          guest.dwellUntil = now + Math.max(1000, waypoint.dwell * 1000);
          if (!guest.investigate) {
            guest.step += 1;
            if (guest.step >= room.guestRoute.length) {
              guest.step = 0;
              guest.loops += 1;
              if (guest.loops >= 1) guest.leaving = true;
            }
          } else {
            guest.investigate = null;
          }
        }
      } else {
        guest.x += (dx / distance) * step;
        guest.y += (dy / distance) * step;
      }
      guest.dir = Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? 3 : 1) : dy > 0 ? 0 : 2;
      guest.moving = true;
    } else {
      guest.moving = false;
    }

    // can this guest see the elephant?
    const elephant = room.elephant;
    const zone = gameMap.zoneAt(Math.floor(guest.x / 32), Math.floor(guest.y / 32));
    const dark = darkZones.includes(zone);
    let sight = guest.sight * (dark ? 0.6 : 1);
    if (guest.kind === "vip") sight += 1.5;
    if (room.complaints.some((entry) => entry.guestId === guest.id)) sight += 2;
    const distanceToElephant = Math.hypot(elephant.x - guest.x, elephant.y - guest.y);
    const spotted =
      distanceToElephant < sight * 32 &&
      gameMap.lineOfSight(guest.x, guest.y, elephant.x, elephant.y, room.doors, Math.ceil(sight) + 2);

    if (!spotted) continue;

    // crowd cover: an employee standing next to it buys everyone time
    const crowd = room.connectedPlayers.some(
      (player) => Math.hypot(player.x - elephant.x, player.y - elephant.y) < CROWD_COVER_RADIUS * 32,
    );
    const hiddenBehindSomething = room.hiddenElephant();
    if (hiddenBehindSomething) continue;

    let rate =
      guest.kind === "vip"
        ? EXPOSURE_RATE_VIP
        : guest.kind === "manager"
          ? EXPOSURE_RATE_MANAGER
          : EXPOSURE_RATE;
    if (elephant.asleep) rate *= 0.6;
    if (crowd) rate *= CROWD_COVER_FACTOR;
    if (guest.alarmed) rate *= 1.35;
    if (dark) rate *= 0.65;

    result.exposurePerSecond += rate;

    if (!guest.alarmed) {
      guest.alarmed = true;
      guest.alarmedUntil = now + 9000;
      const line = room.rng.pick(COMPLAINTS);
      room.addFeed(`😱 ${guest.name}: "${line}"`, "bad", "spot");
      room.raiseNoise(guest.x, guest.y, 12, 9000);
    }

    // record who was closest, for the end-of-match statistics
    let closest: string | null = null;
    let closestDistance = Infinity;
    for (const player of room.connectedPlayers) {
      const distance = Math.hypot(player.x - elephant.x, player.y - elephant.y);
      if (distance < closestDistance) {
        closestDistance = distance;
        closest = player.id;
      }
    }
    result.sightings.push({ guestId: guest.id, witnessId: closest });
  }

  return result;
}

export function soothGuestNear(room: Room, x: number, y: number, radius = 2.2 * 32): Guest | null {
  const now = room.now();
  for (const guest of room.guests) {
    if (Math.hypot(guest.x - x, guest.y - y) > radius) continue;
    const complaint = room.complaints.find((entry) => entry.guestId === guest.id);
    if (!complaint) continue;
    guest.soothedUntil = now + 60_000;
    guest.alarmed = false;
    room.complaints = room.complaints.filter((entry) => entry.guestId !== guest.id);
    room.addFeed(`🙏 Someone apologised to ${guest.name}. They have calmed down.`, "good", "ding");
    return guest;
  }
  return null;
}

export function guestNames(): string[] {
  return [...NAMES];
}
